#!/usr/bin/env node

/**
 * Test script to demonstrate the novel-aware chunking strategy
 * This shows how your proposed approach works in practice
 */

import { EnhancedDocumentService } from './src/services/enhancedDocumentService.js';

// Sample novel excerpt (simulating a 200k word novel structure)
const sampleNovelText = `
CHAPTER 1: THE BEGINNING

The morning sun cast long shadows across the cobblestone streets of the old city. Maria walked slowly, her footsteps echoing in the empty square.

"Where have you been?" called a voice from behind her.

She turned to see Thomas emerging from the shadows of the cathedral. His face was grave, his usually bright eyes clouded with worry.

"I've been walking," she replied simply. "Thinking about what you said yesterday."

The conversation between them hung heavy in the air, filled with unspoken words and the weight of their shared history.

***

Later that afternoon, the marketplace buzzed with activity. Vendors called out their wares while children darted between the stalls, their laughter mixing with the general din of commerce.

Maria found herself drawn to the old bookstall in the corner, where ancient volumes lay stacked in precarious towers.

"Looking for anything particular?" the elderly proprietor asked, his eyes twinkling with curiosity.

CHAPTER 2: THE DISCOVERY

The following day brought unexpected news. A letter had arrived, bearing the seal of the Royal Academy—something Maria had long dreamed of but never dared to hope for.

Thomas found her in the garden, the letter trembling in her hands.

"What is it?" he asked, though the look on her face already told him everything.

"They've accepted my proposal," she whispered. "The research expedition to the Northern Territories. It's everything I've worked toward."

But even as joy flooded through her, a shadow of doubt crept in. The expedition would take her away for months, perhaps longer.

***

That evening, they sat by the fire, the letter spread between them on the small wooden table. The flames cast dancing shadows on the walls, creating patterns that seemed to mirror the uncertainty in their hearts.

"When do you leave?" Thomas asked finally.

"Six weeks," Maria replied. "There's much to prepare."

CHAPTER 3: THE PREPARATION

The weeks that followed were a whirlwind of activity. Maria threw herself into preparations with characteristic intensity, gathering supplies, reviewing maps, and consulting with other scholars who had ventured into the uncharted territories.

Yet beneath the excitement lay a growing awareness of what she would be leaving behind.
`;

// Mock structure map that would be generated by AdvancedDocumentProcessor
const mockStructureMap = {
  chapters: [
    { number: 1, title: "THE BEGINNING", startLine: 5, endLine: 25 },
    { number: 2, title: "THE DISCOVERY", startLine: 26, endLine: 40 },
    { number: 3, title: "THE PREPARATION", startLine: 41, endLine: 50 }
  ],
  sections: [],
  totalWords: 185000, // Simulating a large novel (above 50k threshold)
  hasDialogue: true,
  documentType: 'novel'
};

// Mock processed document
const mockProcessed = {
  normalizedText: sampleNovelText,
  structureMap: mockStructureMap,
  assets: { images: [], tables: [], footnotes: [] }
};

console.log('🔥 Testing Novel-Aware Chunking Strategy\n');
console.log('📚 Document Analysis:');
console.log(`- Estimated words: ${mockStructureMap.totalWords.toLocaleString()}`);
console.log(`- Chapters: ${mockStructureMap.chapters.length}`);
console.log(`- Has dialogue: ${mockStructureMap.hasDialogue ? 'Yes' : 'No'}`);
console.log(`- Document type: ${mockStructureMap.documentType}\n`);

// Initialize enhanced document service
const enhancedService = new EnhancedDocumentService({
  assetsDir: './assets',
  preserveFormatting: true,
  normalizeUnicode: true
});

try {
  // Test the chunking strategy
  console.log('🧠 Applying Novel-Aware Chunking Strategy...\n');
  
  const chunks = enhancedService.createStructureAwareChunks(mockProcessed);
  
  console.log(`✅ Generated ${chunks.length} intelligent chunks:\n`);
  
  chunks.forEach((chunk, index) => {
    console.log(`📄 Chunk ${index + 1}: ${chunk.id}`);
    console.log(`   Type: ${chunk.type}`);
    console.log(`   Chapter: ${chunk.chapter || 'N/A'}`);
    console.log(`   Scene: ${chunk.scene !== undefined ? chunk.scene : 'N/A'}`);
    console.log(`   Tokens: ~${chunk.tokens}`);
    console.log(`   Structure Level: ${chunk.structureInfo?.level || 'basic'}`);
    console.log(`   Boundaries: ${chunk.structureInfo?.boundaries || 'paragraph'}`);
    console.log(`   Previous Context: ${chunk.previousContext ? 'Yes' : 'No'}`);
    console.log(`   Next Context: ${chunk.nextContext ? 'Yes' : 'No'}`);
    
    // Show special content detection
    if (chunk.translationMetadata?.specialHandling?.length > 0) {
      console.log(`   ⚠️  Special Content: ${chunk.translationMetadata.specialHandling.join(', ')}`);
    }
    
    console.log(`   Preview: "${chunk.text.substring(0, 100)}..."\n`);
  });
  
  // Show chunking strategy benefits
  console.log('🎯 Strategy Benefits Demonstrated:');
  console.log('✓ Preserves chapter boundaries');
  console.log('✓ Maintains scene integrity with *** breaks');
  console.log('✓ Keeps dialogue intact');
  console.log('✓ Provides contextual overlap');
  console.log('✓ Intelligent token management');
  console.log('✓ Hierarchical fallback (chapter → scene → paragraph)');
  console.log('✓ Metadata for translation quality');
  
} catch (error) {
  console.error('❌ Error testing chunking strategy:', error.message);
  console.error(error.stack);
}

console.log('\n📊 Comparison with Basic Approaches:');
console.log('❌ Fixed 512-token chunks: Would cut mid-dialogue, split character names');
console.log('❌ Simple paragraph chunks: Would lose chapter/scene context');
console.log('✅ Novel-aware chunks: Preserves narrative structure + context');

console.log('\n💡 Your Strategy Advantages:');
console.log('• Cost-effective: Smart token usage vs quality trade-off');
console.log('• Context-preserving: Maintains literary flow');
console.log('• Translation-friendly: Keeps related content together');
console.log('• Scalable: Works for 200k+ word novels');
console.log('• Hierarchical: Graceful degradation when needed');
